function loadPage() {
	let params = new URLSearchParams(window.location.search);
	let location = params.get("location");
	if (location && pages[location]) {
		document.getElementById("event-image").src = pages[location].EventImageUrl;
		document.getElementById("event-title").textContent = pages[location].title;
		document.getElementById("event-track").textContent = pages[location].track;
		document.getElementById("OffDate").textContent =
			pages[location].OfficialDates;

		document.getElementById("track").textContent = pages[location].track;
		document.getElementById("flag").className = pages[location].Flag;
		document.getElementById("racetrack-image").src =
			pages[location].Racetrackurl;

		document.querySelectorAll(".date1").forEach((td) => {
			td.textContent = pages[location].Date1;
		});

		document.querySelectorAll(".date2").forEach((td) => {
			td.textContent = pages[location].Date2;
		});

		document.querySelectorAll(".date3").forEach((td) => {
			td.textContent = pages[location].Date3;
		});
	}
}

loadPage();
